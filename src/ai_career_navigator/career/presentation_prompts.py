"""Shared public-copy guidance; does not change evidence or assessment policy."""

PLAIN_LANGUAGE_STYLE = """
SHARED CAREER GUIDANCE STYLE
Write directly to 'you', in clear professional language. An example teaches wording and evidence
boundaries, never a predetermined verdict, competency list or plan. Adapt to the supplied profile
and goal; no required number of strengths, gaps or actions and no forced positive direction.
Explain each strength's relevance briefly without repeating the evidence story. Keep unknown
experience as unconfirmed; do not describe missing information as inability. Preserve partial and
transferable contributions without calling them fully demonstrated. Supporting is not owning,
reviewing is not leading, and generic cloud/API work does not prove microservices architecture.
Keep core work prominent; put unrelated roles and narrow employer context in designated details.
Do not hide an important prerequisite merely because one employer asks for it. Preserve uncertainty,
legal/safety conditions and qualifiers when shortening. No invented deadlines, fixed four-step
roadmap, management duties, certifications or experience. No fixed timeline is a valid choice.
Keep each public field concise and complete; internal IDs belong only in reference fields.
"""

CONCISE_REVIEW_STYLE = """
PUBLIC REVIEW STYLE
For each competency, assign display_dimension from the target expectation, not the candidate's
strengths: TECHNICAL=technical or trade practice; DESIGN=problem solving and solution design;
DELIVERY=delivery and operations; COLLABORATION=communication and collaboration;
LEADERSHIP=leadership and ownership; DOMAIN=business or domain knowledge.
Use one primary group only. Use null for prerequisites or unclear grouping. Do not create
competencies to fill groups, force six dimensions, or change a match to improve the chart.
This is presentation metadata, not a readiness score or a new assessment criterion.
Write for the person making a career decision, not an evidence auditor. Use plain language.
Synthesize the descriptions into a combined picture of the work and expectations. Separate shared
expectations from specialist or optional asks; do not turn a small sample into a universal claim.
Keep rationale to one or two short complete sentences: conclusion plus its decisive reason or
condition. Keep role_picture to two or three short complete sentences describing the shared work,
credible direction and meaningful specialist differences, not a posting-by-posting inventory.
Use capability names rather than evidence quotations or lists of source documents. Keep each
strength explanation, development focus, action and completion check to one concise sentence.
Do not repeat the supporting story across fields. Put each unresolved question or limitation once.
Keep source/candidate IDs, line numbers and UUIDs ONLY in the designated structured reference
fields, never in names, summaries, reasons, questions, actions or completion checks. Preserve all
required reference fields for validation. Individual-posting assessments belong in opportunities,
not the combined narrative. Describe actions for the chosen career direction, not a tour of
employers; keep any employer-specific prerequisite conditional rather than universal.
Preserve uncertainty, material prerequisites, safety conditions, evidence depth and no-fixed-
timeline semantics. Brevity is not permission to remove a condition, invent a fact, inflate a match
or change a verdict. Finish every sentence; do not fill a field until it is truncated.
Group decisive unknowns into up to three direct questions where possible; retain extra questions
only when grouping would lose an essential condition. Do not repeat those questions as gap prose.
Use two short sentences for the core-role overview, not a catalogue of unrelated directions.
Make application steps conditional on meeting the selected employer's requirements; answering a
question alone does not establish readiness. Otherwise defer, develop the specific missing piece
and reassess. Completion can be an apply-or-defer decision, not a forced application.
Respect the selected goal: CURRENT_MARKET_ANALYSIS concerns roles to target now; ROLE_TRANSITION
compares a change of function; TARGET_CAREER_PATH plans toward the chosen destination without
assuming a career change; LEADERSHIP_PROGRESSION compares the relevant leadership scope;
CAREER_EXPLORATION explores possibilities without inventing a destination; CAREER_REASSESSMENT
revisits the current direction without claiming improvement or decline absent comparable history.
""" + PLAIN_LANGUAGE_STYLE

